import 'dotenv/config'
import Database from 'better-sqlite3'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'

/**
 * Emits a portable seed.sql for Cloudflare D1.
 *
 * `scripts/seed.ts` is Node-only — it drives better-sqlite3 directly and
 * cannot touch a remote D1 database. Rather than maintain the permission and
 * role catalogue twice (which would drift, and a drifted permission catalogue
 * means a role that grants nothing), this RUNS the real seed against a
 * throwaway file and dumps the result as INSERT statements.
 *
 * So the catalogue has exactly one definition, and this is a projection of it.
 *
 *   npm run seed:d1                      # writes dist/seed.d1.sql
 *   npx wrangler d1 execute support-platform --remote --file dist/seed.d1.sql
 */

// Order matters: parents before children, because D1 enforces foreign keys.
const TABLES = [
  'sp_permissions',
  'sp_roles',
  'sp_role_permissions',
  'sp_products',
  'sp_product_counters',
  'sp_ticket_statuses',
  'sp_ticket_priorities',
  'sp_tags',
  'sp_teams',
  'sp_inbound_addresses',
  'sp_users',
  'sp_user_product_roles',
]

/**
 * Deliberately NOT dumped:
 *   sp_email_providers / sp_settings — the local bootstrap inserts Mailpit,
 *     which points at 127.0.0.1 and is meaningless in production. Configure a
 *     real provider in the admin UI after deploying.
 *   sp_tickets and everything under it — demo data.
 */

const quote = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (Buffer.isBuffer(v)) return `X'${v.toString('hex')}'`
  return `'${String(v).split("'").join("''")}'`
}

function main() {
  const dir = mkdtempSync(join(tmpdir(), 'sp-d1-seed-'))
  const dbFile = join(dir, 'seed.db')
  const out = process.env.D1_SEED_OUT ?? './dist/seed.d1.sql'

  const env = {
    ...process.env,
    DB_FILE: dbFile,
    // Keep the local Mailpit bootstrap out of the generated file entirely.
    DEFAULT_EMAIL_PROVIDER_TYPE: '',
  }

  console.log('Running the real migrations and seed against a scratch database…')
  execFileSync('npx', ['tsx', 'scripts/migrate.ts'], { env, stdio: 'inherit' })
  execFileSync('npx', ['tsx', 'scripts/seed.ts'], { env, stdio: 'inherit' })

  const db = new Database(dbFile, { readonly: true })
  const lines: string[] = [
    '-- Generated by scripts/generate-d1-seed.ts — do not edit by hand.',
    '-- Regenerate with: npm run seed:d1',
    '--',
    '-- Apply with:',
    '--   npx wrangler d1 execute support-platform --remote --file dist/seed.d1.sql',
    '--',
    '-- Safe to re-run: every statement is INSERT OR IGNORE and no row is deleted.',
    '',
  ]

  let total = 0
  for (const table of TABLES) {
    const rows = db.prepare(`SELECT * FROM ${table}`).all() as Record<string, unknown>[]
    if (!rows.length) continue

    lines.push(`-- ${table} (${rows.length} rows)`)
    const columns = Object.keys(rows[0]!)
    for (const row of rows) {
      const values = columns.map((c) => quote(row[c])).join(', ')
      // OR IGNORE rather than a plain INSERT: applying this to a database that
      // already has rows must be a no-op, not an error that aborts the file.
      lines.push(`INSERT OR IGNORE INTO ${table} (${columns.join(', ')}) VALUES (${values});`)
    }
    lines.push('')
    total += rows.length
  }
  db.close()

  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, lines.join('\n'))
  rmSync(dir, { recursive: true, force: true })

  console.log(`\nWrote ${out} — ${total} rows across ${TABLES.length} tables.`)
  console.log(`Admin sign-in: ${process.env.SEED_ADMIN_EMAIL ?? 'admin@support.local'}`)
  console.log(
    process.env.SEED_ADMIN_PASSWORD
      ? '  (password hash taken from SEED_ADMIN_PASSWORD)'
      : '  WARNING: default password ChangeMe!2026 is baked into this file.\n' +
          '  Set SEED_ADMIN_PASSWORD and regenerate before using it in production.',
  )
}

main()
